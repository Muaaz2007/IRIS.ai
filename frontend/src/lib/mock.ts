import { sleep } from './api';
import type { HistoryTurn, SSEEvent } from './types';

/**
 * DEMO BACKEND — emulates the real pipeline locally so the UI is fully
 * explorable before the FastAPI backend exists:
 *
 *   security guard -> ML classifier -> Ollama token stream
 *
 * It emits the exact SSE event shape from docs/API_CONTRACT.md
 * (meta / guard / classify / token / done / error).
 * Delete this file once the real backend is connected — nothing else imports it.
 */

const HARMFUL_TRIGGERS = [
  'hack into',
  'steal',
  'malware',
  'ignore previous instructions',
  'harm someone',
  'bypass security',
];

const CANNED_REPLIES: { match: RegExp; reply: string }[] = [
  {
    match: /pipeline|security|how (do|does) you work/i,
    reply: [
      'You are seeing **IRIS.ai in demo mode** — the backend is not running yet, so responses are mocked locally.',
      '',
      'Once the FastAPI backend is up, every message will flow through this chain:',
      '',
      '1. **Security layer** (`security/`) — screens the prompt; rejected prompts render as a blocked message, never as a model reply.',
      '2. **ML classifier** (`ml/`) — TF-IDF + LogisticRegression flags `benign` vs `harmful` with a confidence score shown next to replies.',
      '3. **Ollama** — generates the response, streamed token-by-token over SSE to this window.',
      '',
      '```python',
      '# backend sketch (FastAPI)',
      'async def chat(payload: ChatRequest):',
      '    if not security_guard.passes(payload.message):',
      '        yield sse("guard", {"passed": False})',
      '        return',
      '    yield sse("guard", {"passed": True})',
      '    yield sse("classify", ml.predict(payload.message))',
      '    async for tok in ollama.stream(payload.message, payload.history):',
      '        yield sse("token", {"text": tok})',
      '    yield sse("done", {"finish_reason": "stop"})',
      '```',
      '',
      'Start it with `uvicorn backend.main:app --reload` and this banner disappears automatically.',
    ].join('\n'),
  },
  {
    match: /ollama|model|llama/i,
    reply: [
      'The chat context is served by **Ollama** running locally.',
      '',
      '- Default endpoint the backend calls: `http://localhost:11434`',
      '- Recommended models: `llama3`, `mistral`, or `qwen2.5` for stronger reasoning.',
      '',
      '```bash',
      'ollama pull llama3',
      'ollama serve',
      '```',
      '',
      'The model name will surface in the sidebar status once `/api/health` reports it — right now this reply is generated by the built-in demo stub.',
    ].join('\n'),
  },
];

const DEFAULT_REPLY = [
  'This is a **mocked response** from the IRIS.ai frontend demo.',
  '',
  'I am here so you can explore the interface — streaming, markdown, code blocks, and the security-blocked state — while the Python backend is being built.',
  '',
  'Try sending a message like *“explain the pipeline”* for a richer demo, or one containing words like *“hack into”* or *“malware”* to see the **security layer blocked** state.',
  '',
  '```json',
  '{ "status": "demo-mode", "backend": "offline", "next_step": "connect FastAPI + Ollama" }',
  '```',
].join('\n');

function buildReply(message: string): string {
  const hit = CANNED_REPLIES.find((c) => c.match.test(message));
  return hit ? hit.reply : DEFAULT_REPLY;
}

/** Word-chunked streaming so the typewriter effect looks natural. */
function tokenize(text: string): string[] {
  return text.match(/\S+\s*/g) ?? [text];
}

export interface MockStreamParams {
  message: string;
  _history: HistoryTurn[];
  signal: AbortSignal;
  onEvent: (event: SSEEvent, data: Record<string, unknown>) => void;
}

export async function mockStreamChat(params: MockStreamParams): Promise<void> {
  const lower = params.message.toLowerCase();
  const harmful = HARMFUL_TRIGGERS.some((w) => lower.includes(w));

  params.onEvent('meta', { conversation_id: 'demo-conversation' });
  await sleep(180);
  if (params.signal.aborted) throw new DOMException('aborted', 'AbortError');

  // 1) Security layer gate
  params.onEvent('guard', { passed: !harmful });
  await sleep(220);
  if (params.signal.aborted) throw new DOMException('aborted', 'AbortError');

  if (harmful) {
    // Rejected prompts never reach the classifier or the model.
    params.onEvent('done', { finish_reason: 'blocked' });
    return;
  }

  // 2) ML classifier badge
  const confidence = Number((0.9 + Math.random() * 0.09).toFixed(2));
  params.onEvent('classify', { label: 'benign', confidence });
  await sleep(120);

  // 3) Ollama-style token stream
  const tokens = tokenize(buildReply(params.message));
  for (const tok of tokens) {
    if (params.signal.aborted) throw new DOMException('aborted', 'AbortError');
    params.onEvent('token', { text: tok });
    await sleep(14 + Math.random() * 22);
  }

  params.onEvent('done', { finish_reason: 'stop' });
}
